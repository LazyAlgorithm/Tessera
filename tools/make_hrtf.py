#!/usr/bin/env python3
"""Turns the MIT KEMAR compact HRTF set (third_party/kemar/compact.zip) into native/tessera_hrtf_data.h.

Each measurement is a pair of 128-sample impulse responses at 44.1 kHz, left ear then right ear, for a source at an
elevation (-40 to 90 degrees) and an azimuth from 0 (ahead) to 180 (behind) on the listener's right. Directions on
the left are the mirror image, with the ears swapped; the engine does that at run time.
"""
import io, re, struct, sys, wave, zipfile
from pathlib import Path

root = Path(__file__).resolve().parent.parent
archive = zipfile.ZipFile(root / 'third_party' / 'kemar' / 'compact.zip')
entries = []
for name in archive.namelist():
    match = re.search(r'H(-?\d+)e(\d+)a\.wav$', name)
    if not match:
        continue
    with wave.open(io.BytesIO(archive.read(name))) as file:
        assert (file.getnchannels(), file.getsampwidth(), file.getframerate(), file.getnframes()) == (2, 2, 44100, 128), name
        samples = struct.unpack('<256h', file.readframes(128))
    entries.append((int(match.group(1)), int(match.group(2)), samples[0::2], samples[1::2]))
entries.sort()
lines = ['// Generated by tools/make_hrtf.py from the MIT KEMAR compact HRTF set. Do not edit.',
         '// Gardner and Martin, "HRTF measurements of a KEMAR", J. Acoust. Soc. Am. 97(6), 1995. Copyright 1994 MIT Media Laboratory.',
         f'#define TN_HRTF_COUNT {len(entries)}', '#define TN_HRTF_TAPS 128', '#define TN_HRTF_RATE 44100',
         '// Elevation and azimuth of each measurement, in degrees.',
         'static const short tn_hrtf_directions[TN_HRTF_COUNT][2] = {']
lines += ['    ' + ' '.join(f'{{{e},{a}}},' for e, a, _, _ in entries[i:i + 12]) for i in range(0, len(entries), 12)]
lines += ['};', '// Left-ear response then right-ear response, 128 samples each.', 'static const short tn_hrtf_responses[TN_HRTF_COUNT][256] = {']
for _, _, left, right in entries:
    lines.append('    {' + ','.join(str(v) for v in left + right) + '},')
lines.append('};')
(root / 'native' / 'tessera_hrtf_data.h').write_text('\n'.join(lines) + '\n')
print(f'wrote {len(entries)} responses')
